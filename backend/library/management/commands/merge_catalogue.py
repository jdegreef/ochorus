"""Resolve a ``ui_catalogues.json`` merge conflict in one command.

``backend/library/data/ui_catalogues.json`` is generated from
``frontend/messages/*`` by ``frontend/scripts/sync-ui-catalogues.mjs``. Every
branch that adds a UI string regenerates the whole file, so two branches in
flight both rewrite it and a plain ``git merge`` conflicts on a file no human
edits by hand — the recurring churn on every UI-string PR.

A git *merge driver* cannot fix this: under merge-ort it runs before the merged
``messages/*`` are on disk, so it would regenerate from the pre-merge state and
auto-commit a wrong file. But once a ``git merge`` has *stopped* on the
conflict, git has already written the working tree — so the merged
``messages/*`` ARE on disk, and regenerating from them now is correct. That is
exactly what this command does: regenerate, then stage the result, turning the
conflict into a one-command resolution.

    git merge origin/main            # stops: CONFLICT in ui_catalogues.json
    cd backend && uv run python manage.py merge_catalogue
    git merge --continue             # (or: resolve any other conflicts first)

It refuses to guess when ``messages/*`` themselves still carry conflict markers
(the regenerator can't parse them) — resolve those first, then re-run. CI's
``sync:catalogues -- --check`` remains the backstop, so a skipped step fails the
build rather than shipping a stale summary.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path

from django.core.management.base import BaseCommand, CommandError

REPO_ROOT = Path(__file__).resolve().parents[4]
SYNC_SCRIPT = REPO_ROOT / "frontend" / "scripts" / "sync-ui-catalogues.mjs"
CATALOGUE = REPO_ROOT / "backend" / "library" / "data" / "ui_catalogues.json"


class Command(BaseCommand):
    help = "Regenerate ui_catalogues.json from the merged messages and stage it."

    def handle(self, *args, **opts):
        node = shutil.which("node")
        if node is None:
            raise CommandError(
                "node is not on PATH — the catalogue is generated by a Node script.\n"
                "Install Node (the frontend needs it too), then re-run."
            )
        if not SYNC_SCRIPT.is_file():
            raise CommandError(f"{SYNC_SCRIPT} is missing")

        # Regenerate from the working-tree messages. The script overwrites the
        # catalogue wholesale, so any conflict markers in the OLD file are simply
        # replaced — no need to pick a side first. It fails, though, if a
        # messages/*.json still has markers (invalid JSON), which is the signal
        # to resolve those first.
        proc = subprocess.run(
            [node, str(SYNC_SCRIPT)], cwd=REPO_ROOT, capture_output=True, text=True, check=False
        )
        if proc.returncode:
            raise CommandError(
                "Regeneration failed. If a messages/*.json still has conflict markers,\n"
                "resolve those first, then re-run — the summary is computed from them.\n\n"
                f"{proc.stderr.strip() or proc.stdout.strip()}"
            )

        # Stage the regenerated file, which is what marks the conflict resolved.
        add = subprocess.run(
            ["git", "add", "--", str(CATALOGUE)],
            cwd=REPO_ROOT, capture_output=True, text=True, check=False,
        )
        if add.returncode:
            raise CommandError(f"git add: {add.stderr.strip()}")

        # Echo the script's own per-locale summary so the operator sees what the
        # merged catalogue now holds.
        summary = proc.stdout.strip()
        if summary:
            self.stdout.write(summary)
        self.stdout.write(self.style.SUCCESS("Regenerated and staged ui_catalogues.json."))
        self.stdout.write("Resolve any other conflicts, then `git merge --continue`.")
