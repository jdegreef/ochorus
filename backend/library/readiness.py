"""Is a language ready to go live? — computed, not remembered.

One place that answers the question, so the admin report, the go-live action and
anyone asking on the command line all agree. Every check is derived from data;
nothing here is a stored verdict that could drift from reality.

**No review gate.** Translations go live wearing their "awaiting native review"
badge, so review state is deliberately not a check — that was an explicit
product decision, not an oversight.

**Thresholds are per-language** and admin-editable (``Language.min_books`` and
friends). A language with a big catalogue behind it should clear a higher bar
than a first beachhead language, and 0 disables a check.

**Why a check can be UNKNOWN.** The Bible check needs a live call to the Take
Root API. If the network is unavailable we report ``unknown`` rather than
``fail`` — "we couldn't ask" is not "the Bible is wrong", and failing closed
here would block a launch for a reason that has nothing to do with the language.

*Interface strings* used to be ``unknown`` too, permanently: they live in
``frontend/messages/*.json`` and the API image is built from ``backend/`` alone,
so the deployed admin could never answer the question — only a failing build
could, after someone had already pressed Go live. The frontend now hands the
answer across as data (``library/data/ui_catalogues.json``, generated by
``frontend/scripts/sync-ui-catalogues.mjs``), and a dev checkout still prefers
the catalogues themselves.

``unknown`` does **not** block readiness, and that is safe rather than lax: the
interface-completeness rule is *also* enforced at build time by
``messageCatalogues.test.ts``, which fails the build for any advertised locale
with a missing key. So a language marked live with an incomplete catalogue fails
its deploy loudly instead of shipping English strings quietly.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from pathlib import Path

from django.conf import settings

from .models import (
    Author,
    AuthorTranslation,
    Book,
    Language,
    Plan,
    Sermon,
    Topic,
    TopicTranslation,
)
from .translation import GLOSSARY_TERMS, missing_glossary_terms

PASS = "pass"
FAIL = "fail"
UNKNOWN = "unknown"
SKIPPED = "skipped"  # threshold set to 0, or not applicable to this language


@dataclass
class Check:
    key: str
    label: str
    status: str
    detail: str
    current: int | None = None
    required: int | None = None

    @property
    def blocking(self) -> bool:
        return self.status == FAIL


@dataclass
class Report:
    code: str
    checks: list[Check] = field(default_factory=list)

    @property
    def ready(self) -> bool:
        """No check is failing. ``unknown`` doesn't block — see the module docstring."""
        return not any(c.blocking for c in self.checks)

    @property
    def blockers(self) -> list[Check]:
        return [c for c in self.checks if c.blocking]

    def as_dict(self) -> dict:
        return {
            "code": self.code,
            "ready": self.ready,
            "blocking": [c.key for c in self.blockers],
            "checks": [asdict(c) for c in self.checks],
        }


# --- individual checks --------------------------------------------------------


def _count_check(key: str, label: str, current: int, required: int, noun: str) -> Check:
    if required <= 0:
        return Check(
            key,
            label,
            SKIPPED,
            f"No minimum set — {current} {noun} present.",
            current,
            required,
        )
    ok = current >= required
    return Check(
        key,
        label,
        PASS if ok else FAIL,
        (
            f"{current} of {required} {noun}."
            if ok
            else f"{current} {noun} — needs {required}."
        ),
        current,
        required,
    )


def _bible_check(lang: Language) -> Check:
    if lang.is_source:
        return Check(
            "bible", "Bible", SKIPPED, "English is the source language.", None, None
        )
    if not lang.bible_code:
        return Check(
            "bible",
            "Bible",
            FAIL,
            "No Bible configured — scripture would be omitted from translations.",
        )
    # Imported lazily: this is the only check that touches the network, and the
    # module is imported by admin views that mostly don't need it.
    from .translation import verify_bible_code

    try:
        verify_bible_code(lang.code)
    except ValueError as e:
        # `fetch_chapter` swallows request errors and returns None, so
        # verify_bible_code raises the same ValueError for "wrong code" as for
        # "the API was unreachable". Those must not be reported the same way: a
        # network outage would otherwise read as a broken Bible and block a
        # launch for a reason that has nothing to do with the language. Probe
        # reachability to tell them apart.
        if not api_reachable():
            return Check(
                "bible",
                "Bible",
                UNKNOWN,
                (
                    f"Could not reach the Bible API to verify {lang.bible_code}. "
                    "Re-run this check from somewhere with access."
                ),
            )
        return Check("bible", "Bible", FAIL, str(e))
    return Check("bible", "Bible", PASS, f"{lang.bible_label or lang.bible_code} resolves.")


def _attribution_check(lang: Language) -> Check:
    """A licensed Bible must be credited before the language is advertised.

    Every Bible in the library was public domain until Hindi, so this check
    passes vacuously for most languages and that is the point: it exists for the
    one case where going live incurs an obligation. `bible_licence` non-blank is
    the declaration that quoting this text costs something; `bible_attribution`
    is what we pay. Failing when the second is missing is the whole check.

    It is deliberately NOT a network call and NOT a judgement about whether the
    licence really requires credit — that decision belongs to whoever chose the
    Bible, and it is recorded in ``language_seed.py`` beside the code itself.

    **What this check cannot see**, said plainly because it is a real limit: the
    line readers get is rendered from ``frontend/src/lib/bibleCredit.ts``, and
    the API image is built from ``backend/`` alone, so a passing check means
    "a credit is configured", not "a credit is on screen". For repo-defined
    languages the two are pinned together by ``tests_bible_credit``. For an
    admin-created one the detail below is the only prompt, which is why it names
    the file. The static map is still the right home: a licence notice fetched
    at run time is a licence notice that is missing whenever the fetch fails.
    """
    if lang.is_source or not lang.bible_licence:
        return Check(
            "attribution",
            "Bible attribution",
            SKIPPED,
            "Public-domain Bible — nothing to credit."
            if not lang.is_source
            else "English is the source language.",
        )
    if not lang.bible_attribution.strip():
        return Check(
            "attribution",
            "Bible attribution",
            FAIL,
            (
                f"{lang.bible_label or lang.bible_code} is licensed "
                f"({lang.bible_licence}) but no credit line is configured. "
                "Readers would see its wording with nothing crediting it."
            ),
        )
    return Check(
        "attribution",
        "Bible attribution",
        PASS,
        (
            f"{lang.bible_licence} credit line configured. Confirm the same text "
            "is in frontend/src/lib/bibleCredit.ts — that is what renders it."
        ),
    )


def api_reachable() -> bool:
    """Whether the Take Root API answered at all — not whether a code is valid."""
    import requests

    from .translation import TAKEROOT_API

    try:
        requests.get(TAKEROOT_API, timeout=5)
        return True
    except requests.RequestException:
        return False


def _glossary_check(lang: Language) -> Check:
    if lang.is_source:
        return Check(
            "glossary", "Glossary", SKIPPED, "English is the source language.", None, None
        )
    missing = missing_glossary_terms(lang.glossary)
    have = len(GLOSSARY_TERMS) - len(missing)
    if missing:
        return Check(
            "glossary",
            "Glossary",
            FAIL,
            f"{len(missing)} term(s) missing: {', '.join(missing)}.",
            have,
            len(GLOSSARY_TERMS),
        )
    return Check(
        "glossary",
        "Glossary",
        PASS,
        f"All {len(GLOSSARY_TERMS)} theological terms defined.",
        have,
        len(GLOSSARY_TERMS),
    )


def _bios_present(code: str, is_source: bool) -> int:
    if is_source:
        return Author.objects.exclude(bio="").exclude(is_imprint=True).count()
    # A bio counts if either the short or the long form exists in this language —
    # they are translated in separate passes.
    return (
        AuthorTranslation.objects.filter(language=code)
        .exclude(bio="", bio_html="")
        .values("author_id")
        .distinct()
        .count()
    )


def _topics_check(lang: Language) -> Check:
    total = Topic.objects.filter(is_published=True).count()
    if not lang.require_all_topics:
        return Check("topics", "Topic shelves", SKIPPED, "Not required for this language.")
    if lang.is_source:
        return Check(
            "topics", "Topic shelves", PASS, f"All {total} shelves are English originals."
        )
    have = (
        TopicTranslation.objects.filter(language=lang.code)
        .exclude(title="")
        .values("topic_id")
        .distinct()
        .count()
    )
    if have >= total:
        return Check("topics", "Topic shelves", PASS, f"All {total} translated.", have, total)
    return Check(
        "topics",
        "Topic shelves",
        FAIL,
        (
            f"{have} of {total} translated — an untranslated shelf is hidden in this "
            "language, so the topics page would be short."
        ),
        have,
        total,
    )


def _messages_dir() -> Path | None:
    """The frontend's message catalogues, when this process can see them."""
    root = Path(settings.BASE_DIR).parent / "frontend" / "messages"
    return root if root.is_dir() else None


#: Completeness summary generated by frontend/scripts/sync-ui-catalogues.mjs.
#: Inside backend/, so the API image contains it (render.yaml builds that image
#: from backend/ alone, which is why reading the catalogues directly can't work
#: in production).
CATALOGUE_SUMMARY = Path(__file__).resolve().parent / "data" / "ui_catalogues.json"


def _ui_counts(code: str) -> tuple[int, int] | None:
    """(present, total) interface strings for ``code``, or None if unknowable.

    Two sources, preferred in this order:

    1. The catalogues themselves, in a dev checkout — always current, no chance
       of disagreeing with the files a build will actually compile.
    2. The generated summary committed into ``backend/``, which is what the
       deployed API has. It is regenerated by an npm script and pinned by
       ``messageCatalogues.test.ts``, so a stale one fails CI rather than
       quietly reporting a language ready on the strength of an old catalogue.

    A missing catalogue is ``(0, total)`` — absent, not unknown. Only "we have
    neither source" returns None.
    """
    msgs = _messages_dir()
    if msgs is not None:
        try:
            base = {
                k for k in json.loads((msgs / "en.json").read_text("utf-8")) if k[:1] != "$"
            }
            target = msgs / f"{code}.json"
            if not target.exists():
                return 0, len(base)
            have = {k for k in json.loads(target.read_text("utf-8")) if k[:1] != "$"}
            return len(base & have), len(base)
        except (OSError, ValueError):
            pass  # fall through to the summary rather than reporting unknown

    try:
        data = json.loads(CATALOGUE_SUMMARY.read_text("utf-8"))
        total = int(data["base_keys"])
        row = data["locales"].get(code)
        return (0 if row is None else int(row["present"])), total
    except (OSError, ValueError, KeyError, TypeError):
        return None


def _ui_check(lang: Language) -> Check:
    if lang.is_source:
        return Check("ui", "Interface strings", SKIPPED, "English is the source.")
    if not lang.require_complete_ui:
        return Check("ui", "Interface strings", SKIPPED, "Not required for this language.")

    counts = _ui_counts(lang.code)
    if counts is None:
        return Check(
            "ui",
            "Interface strings",
            UNKNOWN,
            (
                "No catalogue data available here. Enforced at build time instead: "
                "a live locale with a missing key fails the build."
            ),
        )
    present, total = counts
    if present >= total:
        return Check("ui", "Interface strings", PASS, f"All {total} translated.", total, total)
    if present == 0:
        return Check(
            "ui", "Interface strings", FAIL, f"No {lang.code} catalogue.", 0, total
        )
    return Check(
        "ui",
        "Interface strings",
        FAIL,
        f"{total - present} string(s) would render in English.",
        present,
        total,
    )


# --- the report ---------------------------------------------------------------


def report(lang: Language) -> Report:
    """Every readiness check for one language."""
    code = lang.code
    checks = [
        _bible_check(lang),
        _attribution_check(lang),
        _glossary_check(lang),
        _ui_check(lang),
        _count_check(
            "books",
            "Books",
            Book.objects.filter(language=code, is_published=True).count(),
            lang.min_books,
            "books",
        ),
        _count_check(
            "sermons",
            "Sermons",
            Sermon.objects.filter(language=code, is_published=True).count(),
            lang.min_sermons,
            "sermons",
        ),
        _count_check(
            "bios",
            "Biographies",
            _bios_present(code, lang.is_source),
            lang.min_bios,
            "biographies",
        ),
        _count_check(
            "plans",
            "Reading plans",
            Plan.objects.filter(language=code, is_published=True).count(),
            lang.min_plans,
            "plans",
        ),
        _topics_check(lang),
    ]
    return Report(code=code, checks=checks)
