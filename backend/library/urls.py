from django.urls import path

from .views import (
    ArticleDetailView,
    ArticleListView,
    AuthorDetailView,
    AuthorListView,
    BookDetailView,
    BookEpubView,
    BookListView,
    ChapterDetailView,
    LanguageListView,
    OriginalsView,
    PlanDetailView,
    PlanListView,
    PopularSearchesView,
    QuoteAuthorsView,
    QuoteAuthorTopicView,
    QuotePageView,
    QuoteResolveView,
    QuoteTopicDetailView,
    QuoteTopicPagesView,
    QuoteTopicsView,
    ScriptureGraphView,
    ScripturePagesView,
    ScriptureView,
    SearchClickView,
    SearchView,
    SeriesDetailView,
    SeriesListView,
    SermonDetailView,
    SermonListView,
    TopicDetailView,
    TopicListView,
)

urlpatterns = [
    path("authors/", AuthorListView.as_view(), name="author-list"),
    path("authors/<slug:slug>/", AuthorDetailView.as_view(), name="author-detail"),
    path("originals/", OriginalsView.as_view(), name="originals"),
    path("books/", BookListView.as_view(), name="book-list"),
    path("sermons/", SermonListView.as_view(), name="sermon-list"),
    path("languages/", LanguageListView.as_view(), name="language-list"),
    path("search/", SearchView.as_view(), name="search"),
    path("popular-searches/", PopularSearchesView.as_view(), name="popular-searches"),
    path("search-click/", SearchClickView.as_view(), name="search-click"),
    path("quotes/", QuoteAuthorsView.as_view(), name="quote-authors"),
    # Before quotes/<author>/ so "resolve" is never read as an author slug. The
    # reader's saved-quotes shelf POSTs its stored slugs here.
    path("quotes/resolve/", QuoteResolveView.as_view(), name="quote-resolve"),
    # The theme vocabulary lives under its own prefix so a theme slug can never
    # be mistaken for an author under quotes/<author>/. "pages" before <topic>,
    # like scripture/pages/ — it is one segment, they are the build's page list.
    path("quote-topics/", QuoteTopicsView.as_view(), name="quote-topic-list"),
    path("quote-topics/pages/", QuoteTopicPagesView.as_view(), name="quote-topic-pages"),
    path("quote-topics/<slug:topic>/", QuoteTopicDetailView.as_view(), name="quote-topic-detail"),
    path("quotes/<slug:author>/", QuotePageView.as_view(), name="quote-page"),
    # Three segments, so it cannot collide with the two-segment author page.
    path(
        "quotes/<slug:author>/<slug:topic>/",
        QuoteAuthorTopicView.as_view(),
        name="quote-author-topic",
    ),
    path("scripture/", ScriptureView.as_view(), name="scripture"),
    # Before the <book> patterns: "pages" is one segment, they are two or three,
    # so these cannot actually collide — the order is for a reader of this file.
    path("scripture/pages/", ScripturePagesView.as_view(), name="scripture-pages"),
    path(
        "scripture/<slug:book>/<int:chapter>/",
        ScriptureGraphView.as_view(),
        name="scripture-chapter",
    ),
    path(
        "scripture/<slug:book>/<int:chapter>/<int:verse>/",
        ScriptureGraphView.as_view(),
        name="scripture-verse",
    ),
    path("plans/", PlanListView.as_view(), name="plan-list"),
    path("plans/<slug:slug>/", PlanDetailView.as_view(), name="plan-detail"),
    path("series/", SeriesListView.as_view(), name="series-list"),
    path("series/<slug:slug>/", SeriesDetailView.as_view(), name="series-detail"),
    path("topics/", TopicListView.as_view(), name="topic-list"),
    path("topics/<slug:slug>/", TopicDetailView.as_view(), name="topic-detail"),
    path("articles/", ArticleListView.as_view(), name="article-list"),
    path("articles/<slug:slug>/", ArticleDetailView.as_view(), name="article-detail"),
    path("books/<slug:slug>/", BookDetailView.as_view(), name="book-detail"),
    path(
        "books/<slug:slug>/download.epub",
        BookEpubView.as_view(),
        name="book-epub",
    ),
    path("sermons/<slug:slug>/", SermonDetailView.as_view(), name="sermon-detail"),
    path(
        "books/<slug:slug>/chapters/<int:order>/",
        ChapterDetailView.as_view(),
        name="chapter-detail",
    ),
]
