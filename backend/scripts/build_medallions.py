#!/usr/bin/env python3
"""Cut, tone and write every biography's medallion (`library/medallions.py`).

    uv run python scripts/build_medallions.py

Writes `frontend/static/covers/medallions/<work>.webp` — a square, sepia-toned
crop of the subject's portrait, which `cover-type.css` rounds — and
`frontend/src/lib/coverMedallions.ts`, the list both renderers read. Deterministic:
re-running on unchanged inputs rewrites the same bytes, and
`CoverAssetTests` fails if a medallion is missing, stale or unlisted.
"""

from __future__ import annotations

import io
import sys
from pathlib import Path

BACKEND = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(BACKEND))

from library.medallions import MEDALLIONS, SIZE, Medallion  # noqa: E402

STATIC = BACKEND.parent / "frontend" / "static"
OUT = STATIC / "covers" / "medallions"
TS = BACKEND.parent / "frontend" / "src" / "lib" / "coverMedallions.ts"

#: The sepia the medallion is toned between: a warm near-black and an old
#: paper white, so a photograph sits with a painting rather than on it.
SHADOW, PAPER = (34, 25, 18), (244, 233, 211)


def medallion_bytes(m: Medallion) -> bytes:
    """One medallion as WEBP bytes."""
    from PIL import Image, ImageOps

    photo = Image.open(STATIC / "portraits" / f"{m.portrait}.jpg").convert("L")
    w, h = photo.size
    side = min(round(m.side * h), w, h)
    left = min(max(0, round(m.cx * w - side / 2)), w - side)
    top = min(max(0, round(m.cy * h - side / 2)), h - side)
    crop = photo.crop((left, top, left + side, top + side)).resize((SIZE, SIZE), Image.LANCZOS)
    toned = ImageOps.colorize(ImageOps.autocontrast(crop, cutoff=1), SHADOW, PAPER)
    buf = io.BytesIO()
    toned.save(buf, "WEBP", quality=82, method=6)
    return buf.getvalue()


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    for slug, m in sorted(MEDALLIONS.items()):
        (OUT / f"{slug}.webp").write_bytes(medallion_bytes(m))
        print(f"  {slug}")
    for stale in OUT.glob("*.webp"):
        if stale.stem not in MEDALLIONS:
            stale.unlink()
    body = "\n".join(f"\t'{slug}'," for slug in sorted(MEDALLIONS))
    TS.write_text(
        "// GENERATED by backend/scripts/build_medallions.py — do not edit by hand.\n"
        "//\n"
        "// The biographies whose covers wear their subject's portrait in a medallion\n"
        "// above the title (`library/medallions.py`, `cover-type.css` `.medallion`).\n"
        "// Keyed by work slug, so every language edition of the work wears it.\n\n"
        "export const COVER_MEDALLIONS: ReadonlySet<string> = new Set([\n" + body + "\n]);\n\n"
        "/** The medallion image for one work, or null. */\n"
        "export function medallionFor(slug: string): string | null {\n"
        "\treturn COVER_MEDALLIONS.has(slug) ? `/covers/medallions/${slug}.webp` : null;\n"
        "}\n"
    )
    print(f"wrote {len(MEDALLIONS)} medallions and {TS.name}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
