/**
 * Measure the dark bars along the edges of the painted grounds, and write
 * `src/lib/groundBars.ts`.
 *
 *     cd frontend && npm run covers:bars            # rewrite the table
 *     cd frontend && npm run covers:bars -- --check # fail if it is stale
 *
 * WHY. Many of the museum scans under `static/covers/art/` arrive letterboxed:
 * a band of flat near-black along the top and bottom of the photograph, from
 * the scan or the frame. Under the framed composition's scrim nobody sees it.
 * A LAYOUT (`coverLayouts.ts`) shows the painting unshaded, and there it reads
 * as a black stripe across the top of the picture.
 *
 * So each ground's bars are measured here, once, and a laid-out cover crops
 * just past its own — rather than every painting being cropped by the worst
 * one's amount, or the bars being guessed at by eye.
 *
 * WHAT COUNTS AS A BAR: a run of rows (or columns) in from an edge that are
 * both DARK and FLAT — mean luminance under 40 and a standard deviation under
 * 12. Flat is the point: a dark painting has texture in its shadows, a scan
 * border has none. Capped at 10% of the side, so a genuinely black sky is
 * cropped by no more than that.
 *
 * The number recorded is the deepest bar on any side, as a fraction of that
 * side: the ground is scaled from its centre, so one number crops all four.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import sharp from 'sharp';

const HERE = dirname(fileURLToPath(import.meta.url));
const ART = resolve(HERE, '../static/covers/art');
const OUT = resolve(HERE, '../src/lib/groundBars.ts');

const DARK = 40;
const FLAT = 12;
const CAP = 0.1;
/** Bars thinner than this are left to the layouts' baseline crop. */
const FLOOR = 0.02;

async function measure(file) {
	const { data, info } = await sharp(file).greyscale().raw().toBuffer({ resolveWithObject: true });
	const { width: w, height: h } = info;
	const flatDark = (n, at) => {
		let sum = 0;
		let sq = 0;
		for (let i = 0; i < n; i++) {
			const v = at(i);
			sum += v;
			sq += v * v;
		}
		const mean = sum / n;
		return mean < DARK && Math.sqrt(Math.max(0, sq / n - mean * mean)) < FLAT;
	};
	const depth = (side, line) => {
		let k = 0;
		while (k < side * CAP && line(k)) k++;
		return k / side;
	};
	const row = (y) => flatDark(w, (x) => data[y * w + x]);
	const col = (x) => flatDark(h, (y) => data[y * w + x]);
	return Math.max(
		depth(h, (k) => row(k)),
		depth(h, (k) => row(h - 1 - k)),
		depth(w, (k) => col(k)),
		depth(w, (k) => col(w - 1 - k))
	);
}

async function table() {
	const rows = [];
	for (const file of readdirSync(ART)
		.filter((f) => f.endsWith('.jpg'))
		.sort()) {
		const bar = await measure(resolve(ART, file));
		// Rounded UP to the half-percent, so the crop always clears the bar.
		if (bar >= FLOOR) rows.push([file.replace(/\.jpg$/, ''), Math.ceil(bar * 200) / 200]);
	}
	return rows;
}

function source(rows) {
	return `// GENERATED by scripts/measure-ground-bars.mjs — do not edit by hand.
//
// The flat dark bars along the edges of each painted ground, as the deepest
// bar's fraction of its side. A laid-out cover crops just past them; the framed
// composition's scrim already hides them. \`groundBars.test.ts\` fails when this
// no longer matches the files: run \`npm run covers:bars\`.

export const GROUND_BARS: Record<string, number> = {
${rows.map(([slug, bar]) => `\t'${slug}': ${bar.toFixed(3)}`).join(',\n')}
};

/** The bar to crop past for a painted ground's url; 0 for anything else. */
export function groundBar(coverUrl: string | null | undefined): number {
	const m = /^\\/covers\\/art\\/([^/]+)\\.jpg$/.exec(coverUrl ?? '');
	return (m && GROUND_BARS[m[1]]) || 0;
}
`;
}

const text = source(await table());
if (process.argv.includes('--check')) {
	if (readFileSync(OUT, 'utf8') !== text) {
		console.error('src/lib/groundBars.ts is stale — run `npm run covers:bars`');
		process.exit(1);
	}
} else {
	writeFileSync(OUT, text);
	console.log(`wrote ${OUT}`);
}
