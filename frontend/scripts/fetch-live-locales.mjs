/**
 * Fetch the LIVE locales from the API and write them into the build.
 *
 * Which locales the site advertises used to be a hand-maintained array. It is
 * now a decision recorded in the Language registry (an admin presses Go live),
 * and this script is how that decision reaches a *static* build: the reader is
 * prerendered, so the list has to be baked in at build time — the browser can't
 * discover it later.
 *
 * FAILS THE BUILD LOUDLY if the API can't be reached or answers something
 * implausible. That is deliberate. The alternative — carry on with the
 * last-known list — silently ships a site whose sitemap and hreflang disagree
 * with what the registry says is live, and nobody finds out until search
 * engines do. A red build is a worse morning and a better outcome.
 *
 * Run automatically before `vite build` (see package.json). Output is committed
 * so `svelte-check` and the unit tests have something to import before a build
 * has ever run; the build overwrites it with the live truth.
 */

import { writeFileSync, readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, '..', 'src', 'lib', 'live-locales.generated.ts');
const INLANG = join(HERE, '..', 'project.inlang', 'settings.json');

const API = (process.env.PUBLIC_API_BASE_URL || '').replace(/\/+$/, '');
const ENDPOINT = `${API}/api/library/languages/?all=1`;

/** Exit with a message that says what broke and what to do about it. */
function die(what, detail) {
	console.error(`\n✗ live locales: ${what}\n  ${detail}\n`);
	console.error(
		'  This decides the sitemap, hreflang and which locales are prerendered, so\n' +
			'  the build stops rather than shipping a list that may be wrong.\n' +
			`  Endpoint: ${ENDPOINT || '(PUBLIC_API_BASE_URL unset)'}\n`
	);
	process.exit(1);
}

if (!API) {
	die(
		'PUBLIC_API_BASE_URL is not set',
		'The build needs the API to ask which languages are live.'
	);
}

let payload;
try {
	const res = await fetch(ENDPOINT, { signal: AbortSignal.timeout(20_000) });
	if (!res.ok) die(`the API answered ${res.status}`, 'Expected 200 with a JSON array.');
	payload = await res.json();
} catch (e) {
	die('could not reach the API', e instanceof Error ? e.message : String(e));
}

if (!Array.isArray(payload) || payload.length === 0) {
	die('the API returned no languages', `Got: ${JSON.stringify(payload).slice(0, 200)}`);
}

const codes = payload.map((row) => row?.code).filter((c) => typeof c === 'string' && c);
if (codes.length !== payload.length) {
	die('a language row had no code', JSON.stringify(payload).slice(0, 200));
}
if (!codes.includes('en')) {
	// English is the source language and the x-default target. Its absence means
	// we're talking to the wrong database, not that English was retired.
	die('English is missing from the live set', `Got: ${codes.join(', ')}`);
}

// Every live locale must also be a compiled UI locale, or the app cannot build
// a URL for it: `localizeHref` only knows the locales Paraglide compiled. An
// admin CAN launch a language whose UI locale was never added — this is the
// check that turns that into a clear build failure instead of broken links.
let uiLocales = [];
try {
	uiLocales = JSON.parse(readFileSync(INLANG, 'utf-8')).locales ?? [];
} catch (e) {
	die('could not read project.inlang/settings.json', String(e));
}
const notWired = codes.filter((c) => !uiLocales.includes(c));
if (notWired.length) {
	die(
		`live locale(s) with no UI locale: ${notWired.join(', ')}`,
		'Add them to project.inlang/settings.json (and translate messages/<code>.json), ' +
			'or set the language back to draft in the admin. Without a compiled locale the ' +
			'app cannot generate URLs for it.'
	);
}

// The endpoint already carries each language's autonym, and we used to drop it
// on the floor and keep a second copy by hand in lang.svelte.ts. That map was
// the last survivor of the four hand-synced language lists the Language model's
// docstring describes — so take the name while we are here. Only non-empty
// strings: a registry row with a blank autonym falls through to the hand map
// rather than rendering nothing.
const names = Object.fromEntries(
	payload
		.filter((row) => typeof row?.native_name === 'string' && row.native_name.trim())
		.map((row) => [row.code, row.native_name.trim()])
);

const banner = `// GENERATED by scripts/fetch-live-locales.mjs — do not edit by hand.
//
// The locales the Language registry says are LIVE. Regenerated before every
// build from the API, so an admin pressing "Go live" reaches the static site on
// the next deploy. Committed so type-checking and tests work before a build.
//
// EXPECT THIS LIST TO LAG PRODUCTION. It is refreshed only when someone runs a
// build and commits the result, so between an admin pressing "Go live" and the
// next commit of this file, the deployed site advertises a locale that is not
// named here. That is not a bug and does not need a hand-edit: the build
// overwrites this from the API before every deploy. Read it as "the last list
// someone happened to commit", never as "what the site currently advertises" —
// checking the registry, or the live footer, is how you answer that.
`;
writeFileSync(
	OUT,
	`${banner}export const LIVE_LOCALES = ${JSON.stringify(codes)} as const;\n\n` +
		'// Each live language\'s autonym, as the registry holds it. The reader\n' +
		'// prefers these over the hand-maintained map in lang.svelte.ts, so\n' +
		'// correcting a name in the admin reaches the picker on the next build.\n' +
		`export const LIVE_LOCALE_NAMES: Record<string, string> = ${JSON.stringify(names)};\n`,
	'utf-8'
);
console.log(`✓ live locales: ${codes.join(', ')}`);
