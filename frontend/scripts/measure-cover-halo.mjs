/**
 * How dark the halo is just outside a letter — `npm run covers:halo`.
 *
 * `cover-type.css` gives the white type over a painting its own soft shadow
 * (THE HALO). The contrast gate (`covers.ink_contrast`) counts it, so it needs a
 * number it can trust: per ink region, the LEAST darkness the halo lays on the
 * pixels just outside a glyph's edge, which is the background a glyph's
 * contrast is read against.
 *
 * Measured, every framed edition, two renders each with the painting and the
 * bands switched off:
 *   - the type alone, over black, no halo — where the glyphs are;
 *   - the type with its halo, over white — how dark the halo leaves the paint.
 * The ring is the pixels inside a line's box that no glyph touches but one sits
 * within RING px of (the pixel that touches it); a region's floor is the least halo darkness found on any
 * ring pixel of any edition (after dropping the faintest 0.5% — the antialiased
 * tips of hairline serifs, where a glyph's own ink is fading too).
 *
 * Writes `backend/library/cover_halo.py`: the floors, and the digest of the
 * halo rules they were measured from, which `coverHalo.test.ts` holds the
 * stylesheet to.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { chromium } from 'playwright';
import sharp from 'sharp';
import { HEIGHT, STATIC, WIDTH, coverPage, made, measureInk, needTwins } from './generate-cover-og.mjs';
import { haloDigest } from '../src/lib/coverHalo.ts';

const CSS = readFileSync(resolve(import.meta.dirname, '../src/lib/components/cover-type.css'), 'utf8');
const OUT = resolve(import.meta.dirname, '../../backend/library/cover_halo.py');
const RING = 1;
const DROP = 0.005;

const BARE = `.ground,.cover-ground{visibility:hidden!important}
.cover-plate.over-art::before,.cover-plate.over-art .cover-type .middle::after{display:none!important}`;
const MASK = `${BARE}.card{background:#000}.cover-type *{text-shadow:none!important;box-shadow:none!important}.cover-type .brandmark svg{filter:none!important}`;
const LIT = `${BARE}.card{background:#fff}`;

async function grey(page, css, html) {
	await page.setContent(html);
	await page.addStyleTag({ content: css });
	await page.evaluate(() => document.fonts.ready);
	return sharp(await page.screenshot({ type: 'png' })).greyscale().raw().toBuffer();
}

const books = needTwins().filter((b) => b.art);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: WIDTH, height: HEIGHT }, deviceScaleFactor: 1 });
const samples = {};
let n = 0;
for (const book of books) {
	const groundBytes = readFileSync(resolve(STATIC, book.cover.replace(/^\//, '')));
	if (!['framed', 'framed-top'].includes(made(book, groundBytes).layout)) continue;
	const html = coverPage(book, groundBytes);
	const mask = await grey(page, MASK, html);
	const { rows } = await measureInk(page);
	const lit = await grey(page, LIT, html);
	for (const [region, boxes] of Object.entries(rows)) {
		const got = (samples[region] ??= []);
		for (const [x0, y0, x1, y1] of boxes) {
			for (let y = Math.max(0, y0); y < Math.min(HEIGHT, y1); y++) {
				for (let x = Math.max(0, x0); x < Math.min(WIDTH, x1); x++) {
					if (mask[y * WIDTH + x] > 8) continue;
					let near = false;
					for (let dy = -RING; dy <= RING && !near; dy++) {
						for (let dx = -RING; dx <= RING; dx++) {
							const yy = y + dy, xx = x + dx;
							if (yy >= 0 && yy < HEIGHT && xx >= 0 && xx < WIDTH && mask[yy * WIDTH + xx] > 200) { near = true; break; }
						}
					}
					if (near) got.push(1 - lit[y * WIDTH + x] / 255);
				}
			}
		}
	}
	if (++n % 50 === 0) console.log(`  ${n} editions`);
}
await browser.close();

const floor = {};
for (const [region, values] of Object.entries(samples)) {
	values.sort((a, b) => a - b);
	floor[region] = Math.floor(100 * values[Math.floor(values.length * DROP)]) / 100;
	console.log(`${region.padEnd(9)} floor ${floor[region].toFixed(2)}  (min ${values[0].toFixed(2)}, median ${values[values.length >> 1].toFixed(2)}, ${values.length} ring px)`);
}
writeFileSync(
	OUT,
	`"""The halo's floor — GENERATED by \`npm run covers:halo\` (frontend/scripts/measure-cover-halo.mjs).

Per ink region: the least darkness the halo (\`cover-type.css\`, THE HALO) lays on
the paint just outside a glyph, measured over every framed edition (${n}) with the
faintest ${DROP * 100}% of ring pixels dropped. \`covers.ink_contrast\` composites this much
black over each line it measures, on top of the bands.

\`HALO_RULES\` is the digest of the halo rules this was measured from;
\`coverHalo.test.ts\` fails when the stylesheet's rules no longer match it.
"""

HALO = {
${Object.entries(floor).sort().map(([k, v]) => `    "${k}": ${v.toFixed(2)},`).join('\n')}
}

HALO_RULES = "${haloDigest(CSS)}"
`
);
console.log(`measured ${n} framed editions -> ${OUT}`);
