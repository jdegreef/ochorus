/**
 * Write a summary of interface-catalogue completeness where the API can read it.
 *
 * The readiness report answers "is this language ready to go live?", and one of
 * its checks is whether the interface is fully translated. That check could only
 * ever be answered in a dev checkout: the message catalogues live in
 * `frontend/messages/`, and the API's Docker image is built from `backend/`
 * alone (render.yaml `rootDir: backend`), so in production it reported `unknown`
 * — forever, for every language. An admin could not tell whether Arabic's
 * interface was done; only a failing build could say so, after the fact.
 *
 * So the frontend hands the fact across the wall as data. This produces a small
 * JSON file inside `backend/`, which the image then contains, and which
 * `library/readiness.py` reads when it cannot see the catalogues themselves.
 *
 * COMMITTED, and kept honest by `messageCatalogues.test.ts`: that test computes
 * the same summary on every CI run and fails if this file disagrees. A stale
 * summary is worse than none — it would report a language ready on the strength
 * of a catalogue that has since grown — so going stale has to break the build,
 * not sit quietly.
 *
 * It records only what each locale is MISSING — no key counts. A count moves on
 * every PR that adds a UI string, so when this file carried `base_keys` and a
 * per-locale `present`, every such PR rewrote the same lines and parallel PRs
 * merge-conflicted on it, and a conflict resolved by keeping either side left a
 * stale copy that broke main's CI (2026-09-23, #3124). A missing-keys list does
 * not move when a key lands in every catalogue — which parity requires — so the
 * file now changes only when a locale is added or genuinely falls behind.
 *
 *   npm run sync:catalogues          rewrite the file
 *   npm run sync:catalogues -- --check   fail if it is out of date (CI)
 */

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const MESSAGES = join(HERE, '..', 'messages');
const OUT = join(HERE, '..', '..', 'backend', 'library', 'data', 'ui_catalogues.json');

const BASE_LOCALE = 'en';

/**
 * Real message keys — `$schema` is metadata, not a string a reader ever sees.
 * @param {string} file
 * @returns {string[]}
 */
const keysOf = (file) =>
	Object.keys(JSON.parse(readFileSync(file, 'utf-8'))).filter((k) => !k.startsWith('$'));

/** @param {string} [messagesDir] */
export function buildSummary(messagesDir = MESSAGES) {
	const locales = readdirSync(messagesDir)
		.filter((f) => f.endsWith('.json'))
		.map((f) => f.replace(/\.json$/, ''))
		.sort();

	const base = keysOf(join(messagesDir, `${BASE_LOCALE}.json`));

	/** @type {Record<string, { missing: string[] }>} */
	const out = {};
	for (const locale of locales) {
		const have = new Set(keysOf(join(messagesDir, `${locale}.json`)));
		// Sorted so the file is stable across machines and the --check diff is
		// about content, not key order.
		out[locale] = { missing: base.filter((k) => !have.has(k)).sort() };
	}

	return {
		_comment:
			'GENERATED by frontend/scripts/sync-ui-catalogues.mjs — do not edit by hand. ' +
			'Run `npm run sync:catalogues` in frontend/ when messageCatalogues.test.ts says it is stale.',
		base_locale: BASE_LOCALE,
		locales: out
	};
}

/** @param {ReturnType<typeof buildSummary>} summary */
const serialize = (summary) => `${JSON.stringify(summary, null, '\t')}\n`;

// Only act when run directly — the test imports `buildSummary` from here so the
// gate and the generator can never compute completeness differently.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
	const next = serialize(buildSummary());
	if (process.argv.includes('--check')) {
		let current = '';
		try {
			current = readFileSync(OUT, 'utf-8');
		} catch {
			/* missing file reads as an empty mismatch below */
		}
		if (current !== next) {
			console.error(
				'\n✗ backend/library/data/ui_catalogues.json is out of date.\n' +
					'  The admin readiness report reads it to say whether a language\'s\n' +
					'  interface is translated, so a stale copy reports the wrong answer.\n' +
					'  Fix: cd frontend && npm run sync:catalogues\n'
			);
			process.exit(1);
		}
		console.log('✓ ui catalogues summary is up to date');
	} else {
		writeFileSync(OUT, next, 'utf-8');
		const line = Object.entries(buildSummary().locales)
			.map(([l, v]) => `${l} ${v.missing.length ? `${v.missing.length} missing` : 'complete'}`)
			.join(' · ');
		console.log(`✓ wrote ${OUT}\n  ${line}`);
	}
}
